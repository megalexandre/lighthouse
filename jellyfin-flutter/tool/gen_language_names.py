#!/usr/bin/env python3
"""Writes lib/l10n/language_names.dart: the name of each language the server
knows, in each of the app's languages.

Tracks and preferences carry an ISO 639 code ("por", "fre"/"fra", "pt"); the
server's own label for it is in English. The names come from Unicode CLDR
(pinned below), the codes from the server's iso6392.txt (the same list
/Localization/Cultures is made from).

  tool/gen_language_names.py [path/to/iso6392.txt]

Adding an app language: add it to APP_LANGUAGES and run this again.
"""

import json
import pathlib
import sys
import urllib.request

CLDR = "46.0.0"
APP_LANGUAGES = ["en", "pt"]

# Not languages (as the server's MediaStream._specialCodes): no name shown.
SPECIAL = {"mis", "mul", "und", "zxx"}

root = pathlib.Path(__file__).resolve().parent.parent
iso = pathlib.Path(
    sys.argv[1]
    if len(sys.argv) > 1
    else root.parent / "jellyfin/Emby.Server.Implementations/Localization/iso6392.txt"
)


def cldr(lang):
    url = (
        f"https://raw.githubusercontent.com/unicode-org/cldr-json/{CLDR}/"
        f"cldr-json/cldr-localenames-full/main/{lang}/languages.json"
    )
    with urllib.request.urlopen(url, timeout=30) as r:
        data = json.load(r)
    return data["main"][lang]["localeDisplayNames"]["languages"]


def first_upper(s):
    return s[:1].upper() + s[1:]


# Each row: T code | B code (when it differs) | ISO 639-1 | English | French.
# A code shows up once per regional variant ("pt-br"): the first row wins.
languages = {}  # main code -> (aliases, CLDR key)
for line in iso.read_text(encoding="utf-8-sig").splitlines():
    t, b, two, *_ = line.split("|")
    if not t or t in SPECIAL or t in languages:
        continue
    two = two if two and "-" not in two else ""
    aliases = sorted({c for c in (b, two) if c})
    languages[t] = (aliases, two or t)

names = {lang: cldr(lang) for lang in APP_LANGUAGES}
known = {code: v for code, v in languages.items() if all(v[1] in names[l] for l in APP_LANGUAGES)}


def q(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


out = [
    "// Generated by tool/gen_language_names.py from Unicode CLDR "
    f"{CLDR}: do not edit.",
    "// ignore_for_file: lines_longer_than_80_chars",
    "",
    "/// Other codes for a language (ISO 639-2/B, ISO 639-1) -> its main code",
    "/// (ISO 639-2/T, the keys of [languageNames]).",
    "const languageAliases = <String, String>{",
]
for code, (aliases, _) in sorted(known.items()):
    for a in aliases:
        out.append(f"  {q(a)}: {q(code)},")
out += ["};", "", "/// App language -> main code -> the language's name in it.",
        "const languageNames = <String, Map<String, String>>{"]
for lang in APP_LANGUAGES:
    out.append(f"  {q(lang)}: {{")
    for code, (_, key) in sorted(known.items()):
        out.append(f"    {q(code)}: {q(first_upper(names[lang][key]))},")
    out.append("  },")
out += ["};", ""]

target = root / "lib/l10n/language_names.dart"
target.write_text("\n".join(out), encoding="utf-8")
print(f"{target.relative_to(root)}: {len(known)} languages, of {len(languages)} codes")
