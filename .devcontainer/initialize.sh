#!/usr/bin/env bash
# Runs on the HOST (not in the container), before the containers are built.
# Triggered by "initializeCommand" in devcontainer.json.
#
# It writes .devcontainer/.env. Docker Compose reads that file automatically
# and uses it to fill the ${...} variables in docker-compose.yml.
# This way no user id is hardcoded: the setup adapts to whoever runs it.
set -euo pipefail

env_file="$(dirname "$0")/.env"

# Your user and group ids. The container user "dev" gets the same ids,
# so files it creates in the bind-mounted repo are owned by you on the host.
user_uid="$(id -u)"
user_gid="$(id -g)"

# Group that owns the GPU render nodes (/dev/dri/renderD*).
# The container user joins it to use hardware video decoding (VAAPI).
# Some distros use "video" instead of "render".
render_gid="$(getent group render | cut -d: -f3 || true)"
if [ -z "$render_gid" ]; then
  render_gid="$(getent group video | cut -d: -f3)"
fi

cat > "$env_file" <<EOF
# Generated by initialize.sh. Do not edit or commit.
USER_UID=${user_uid}
USER_GID=${user_gid}
RENDER_GID=${render_gid}
XDG_RUNTIME_DIR=${XDG_RUNTIME_DIR:-/run/user/${user_uid}}
EOF

echo "Wrote ${env_file}:"
cat "$env_file"
